import 'dart:convert';
import 'dart:io';

void main() {
  final output = StringBuffer('// Generated by tool/sync_i18n.dart. Do not edit.\n');
  for (final locale in ['zh-CN', 'en-US']) {
    final data = jsonDecode(File('../i18n/$locale.json').readAsStringSync()) as Map<String, dynamic>;
    final name = locale == 'zh-CN' ? 'zhMessages' : 'enMessages';
    output.writeln('const $name = <String, String>${jsonEncode(data)};');
  }
  final file = File('lib/src/i18n/messages.g.dart');
  file.createSync(recursive: true);
  file.writeAsStringSync(output.toString());
}
